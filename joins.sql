SELECT
	CUSTOMER.FIRST_NAME,
	CUSTOMER.LAST_NAME,
	RENTAL.RENTAL_DATE
FROM
	CUSTOMER
	INNER JOIN RENTAL ON CUSTOMER.CUSTOMER_ID = RENTAL.CUSTOMER_ID
ORDER BY
	RENTAL.RENTAL_DATE
LIMIT
	10;

-- #2 Left join
SELECT
	PAYMENT.PAYMENT_ID,
	CUSTOMER.FIRST_NAME,
	CUSTOMER.LAST_NAME
FROM
	CUSTOMER
	LEFT JOIN PAYMENT ON CUSTOMER.CUSTOMER_ID = PAYMENT.CUSTOMER_ID
ORDER BY
	PAYMENT.PAYMENT_DATE
LIMIT
	10;

--#3 where when
SELECT
	PAYMENT.AMOUNT,
	PAYMENT.PAYMENT_DATE,
	CUSTOMER.FIRST_NAME,
	CUSTOMER.LAST_NAME
FROM
	CUSTOMER
	INNER JOIN PAYMENT ON CUSTOMER.CUSTOMER_ID = PAYMENT.CUSTOMER_ID
WHERE
	PAYMENT.AMOUNT BETWEEN 5 AND 10
ORDER BY
	PAYMENT.PAYMENT_DATE
LIMIT
	10;

--#4 Join with Like
SELECT
	LANGUAGE.NAME,
	FILM.TITLE,
	FILM.RELEASE_YEAR
FROM
	FILM
	INNER JOIN LANGUAGE ON FILM.LANGUAGE_ID = LANGUAGE.LANGUAGE_ID
WHERE
	FILM.TITLE LIKE 'A%'
ORDER BY
	FILM.TITLE
LIMIT
	10;

--#5 Self Join
SELECT
	F1.TITLE AS MOVIE_1,
	F2.TITLE AS MOVIE_2,
	F1.RENTAL_DURATION
FROM
	FILM AS F1
	INNER JOIN FILM AS F2 ON F1.RENTAL_DURATION = F2.RENTAL_DURATION
	AND F1.FILM_ID < F2.FILM_ID
ORDER BY
	F1.TITLE
LIMIT
	10;